import { chromium } from 'playwright'
const BASE = 'http://localhost:4174', OUT = '/workspace/cinema/final', errs = []
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message))
await p.goto(BASE + '/movie/starlight-run')
await p.locator('main section button:not([disabled]):has-text("€")').first().click(); await p.waitForURL(/seats/)
await p.waitForSelector('canvas', { timeout: 20000 }); await p.waitForTimeout(2000)
const seat = p.locator('[data-seat][aria-label^="Row E"][aria-label*="free"]').nth(6)
const box = await seat.boundingBox(); console.log('mobile seat hit box', box.width, box.height)
await seat.tap(); await p.waitForTimeout(1500)
const grid = await p.locator('[data-seatgrid]').boundingBox(); console.log('grid width', grid.width)
await p.screenshot({ path: `${OUT}/seats-mobile-390-selected.png` })
// keyboard check on mobile map
await seat.focus(); await p.keyboard.press('ArrowRight'); console.log('focused after →', await p.evaluate(() => document.activeElement?.getAttribute('aria-label')))
// mobile sheet: focus trap + Esc + return
await p.goto(BASE + '/'); await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300)
await p.screenshot({ path: `${OUT}/dialog-mobile-menu-sheet.png` })
for (let i = 0; i < 6; i++) await p.keyboard.press('Tab')
console.log('focus inside sheet after 6 tabs', await p.evaluate(() => !!document.activeElement?.closest('[role=dialog]')))
await p.keyboard.press('Escape'); await p.waitForTimeout(200)
console.log('after Esc focus returns to', await p.evaluate(() => document.activeElement?.getAttribute('aria-label')))
await ctx.close()
const d = await b.newPage({ viewport: { width: 1440, height: 900 } })
await d.goto(BASE + '/movie/neon-alley'); await d.getByRole('button', { name: /Watch trailer/ }).click(); await d.waitForTimeout(300)
await d.screenshot({ path: `${OUT}/dialog-trailer-desktop-1440.png` })
await d.keyboard.press('Escape'); await d.waitForTimeout(200)
console.log('trailer Esc closes:', await d.locator('[role=dialog]').count() === 0, 'focus back:', await d.evaluate(() => document.activeElement?.textContent))
await b.close(); console.log('errors', errs)
